"""Import the current game's painted art; retain lossless full-resolution masters.

Usage: python tools/import-neon-demo-art.py PATH_TO_GODOT_PROJECT
The embedded previews are deliberately smaller display derivatives, not replacements
for the originals. They make the scene playable before external images arrive.
"""
import base64
from io import BytesIO
import hashlib
import json
from pathlib import Path
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
GAME = Path(sys.argv[1]).resolve()
DEST = ROOT / 'assets/demo/neon-comic'
DEST.mkdir(parents=True, exist_ok=True)
SOURCES = {
    'stand': 'assets/ui/comic_menu/hero_stand.webp',
    'flight': 'assets/ui/comic_menu/hero.webp',
    'climb': 'assets/ui/comic_menu/hero_wall.webp',
    'far': 'assets/backgrounds/comic_worlds/solar_far.webp',
    'mid': 'assets/backgrounds/comic_worlds/solar_mid.webp',
    'near': 'assets/backgrounds/comic_worlds/solar_near.webp',
    'coin': 'assets/ui/comic_menu/coin_sheet.webp',
    'trail': 'assets/player/energy_boy_v2/trail_classic_v2.webp',
}
manifest = {}
for key, source in SOURCES.items():
    image = Image.open(GAME / source)
    if key == 'coin':
        # Godot's first atlas cell, including its transparent filtering guard.
        w, h = image.size
        image = image.crop((round(w*.01), round(h*.01), round(w/3-w*.01), round(h/3-h*.01)))
    original = DEST / f'{key}-original.webp'
    image.save(original, 'WEBP', lossless=True, method=6, exact=True)
    display = image.copy()
    display.thumbnail((480, 854) if key in ('far', 'mid', 'near') else (384, 384), Image.Resampling.LANCZOS)
    path = DEST / f'{key}.webp'
    display.save(path, 'WEBP', lossless=True, method=6, exact=True)
    preview = image.copy()
    preview.thumbnail((96, 171) if key in ('far', 'mid', 'near') else (160, 160), Image.Resampling.LANCZOS)
    buffer = BytesIO()
    preview.save(buffer, 'WEBP', lossless=True, method=6, exact=True)
    bounds = image.getchannel('A').point(lambda a: 255 if a > 51 else 0).getbbox() if image.mode == 'RGBA' else (0, 0, *image.size)
    manifest[key] = {'source': source, 'size': list(image.size), 'bounds': list(bounds),
        'src': '/assets/demo/neon-comic/' + path.name + '?v=' + hashlib.sha256(path.read_bytes()).hexdigest()[:12],
        'preview': 'data:image/webp;base64,' + base64.b64encode(buffer.getvalue()).decode()}
(DEST / 'art.js').write_text('/* Generated by tools/import-neon-demo-art.py; lossless WebP previews. */\nwindow.NeonDemoArt=' + json.dumps(manifest, separators=(',', ':')) + ';\nwindow.dispatchEvent(new Event("neon:artready"));\n', encoding='utf-8')
print('Imported', len(manifest), 'assets;', (DEST/'art.js').stat().st_size, 'bytes of self-contained previews')
