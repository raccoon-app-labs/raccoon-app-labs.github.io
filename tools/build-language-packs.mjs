import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const normalize=value=>String(value).replace(/\s+/gu,' ').trim();
const json=value=>JSON.stringify(value).replaceAll('<','\\u003c');
const hash=source=>crypto.createHash('sha256').update(source).digest('hex').slice(0,12);
const integrity=source=>'sha256-'+crypto.createHash('sha256').update(source).digest('base64');
const read=file=>fs.readFileSync(path.join(root,file),'utf8').replaceAll('\r\n','\n');
const write=(file,source)=>{const target=path.join(root,file);fs.mkdirSync(path.dirname(target),{recursive:true});if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replaceAll('\r\n','\n')!==source)fs.writeFileSync(target,source);};
const attr=(tag,name)=>tag.match(new RegExp('(?:\\s|^)'+name+'="([^"]+)"'))?.[1];
function set(tag,name,value){const pattern=new RegExp('\\s'+name+'="[^"]*"');return pattern.test(tag)?tag.replace(pattern,` ${name}="${value}"`):tag.replace('>',` ${name}="${value}">`);}
function* pages(dir=root){for(const entry of fs.readdirSync(dir,{withFileTypes:true})){if(entry.name==='.git')continue;const file=path.join(dir,entry.name);if(entry.isDirectory())yield* pages(file);else if(entry.name.endsWith('.html'))yield file;}}
const bundles=new Map();
let pageCount=0;
for(const file of pages()){
 let html=fs.readFileSync(file,'utf8').replaceAll('\r\n','\n');
 let found=false;
 html=html.replace(/<script\b[^>]*src="[^"]+"[^>]*><\/script>/g,tag=>{
  const source=attr(tag,'data-locale-source')||attr(tag,'src')?.split('?')[0];
  if(!/^\/(?:assets\/locales\/p-[\w-]+\.js|plus\/locale-data\.js)$/.test(source))return tag;
  found=true;
  if(!bundles.has(source)){
   const window={};vm.runInNewContext(read(source),{window,Object},{timeout:3000});
   const name=window.HANZI_SITE_MESSAGES?'HANZI_SITE_MESSAGES':'HANZI_PLUS_MESSAGES';
   const data=window[name],aliases=window.HANZI_SOURCE_ALIASES||{};
   const codes=Object.keys(data),foreign=codes.filter(code=>!['en','ru'].includes(code));
   const values=Object.fromEntries(codes.map(code=>[code,new Set(Object.values(data[code]).map(normalize))]));
   const baseAliases=Object.fromEntries(Object.entries(aliases).filter(([key])=>values.en.has(key)||values.ru.has(key)||!foreign.some(code=>values[code].has(key))));
   const id=path.basename(source,'.js'),languages={};
   for(const code of foreign){
    const selected=Object.fromEntries(Object.entries(aliases).filter(([key])=>values[code].has(key)&&!Object.hasOwn(baseAliases,key)));
    // Keep store/checkout-specific overrides installed by later scripts.
    const stable=`(()=>{const data=window.${name};const overrides={...data.${code}};Object.assign(data.${code},${json(data[code])},overrides);Object.assign(window.HANZI_SOURCE_ALIASES||{},${json(selected)});})();\n`;
    const target=`assets/locales/optimized/${id}.${code}.${hash(stable)}.js`;
    write(target,stable);languages[code]={src:'/'+target,integrity:integrity(stable)};
   }
   const base=Object.fromEntries(codes.map(code=>[code,['en','ru'].includes(code)?data[code]:{}]));
   const packed=`/* Generated by tools/build-language-packs.mjs. */\nwindow.${name}=${json(base)};\nwindow.HANZI_SOURCE_ALIASES=${json(baseAliases)};\nwindow.HANZI_LOCALE_PACKS=${json({initial:['en','ru'],languages})};\n`;
   const target=`assets/locales/optimized/${id}.base.js`;write(target,packed);
   bundles.set(source,{src:'/'+target+'?v='+hash(packed),integrity:integrity(packed)});
  }
  const bundle=bundles.get(source);return set(set(set(tag,'src',bundle.src),'integrity',bundle.integrity),'data-locale-source',source);
 });
 if(found){
  const loader=read('assets/locales/load.js');
  html=html.replace(/<script\b[^>]*src="\/assets\/locales\/load\.js[^>]*><\/script>\s*/g,'');
  html=html.replace(/<script\b[^>]*src="\/plus\/locale\.js[^>]*><\/script>/,tag=>`<script src="/assets/locales/load.js?v=${hash(loader)}" defer></script>\n${tag}`);
  write(path.relative(root,file),html);pageCount++;
 }
}
console.log(`Built ${bundles.size} language bundles for ${pageCount} pages; RU/EN are immediate, other languages load on demand.`);
